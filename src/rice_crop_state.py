"""Prepare a manual Earth Engine export and validate its district-year import.

No credentials, cloud actions, outcome-driven selection or model fitting here.
"""
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data/processed/rice/crop_state"
RAW = ROOT / "data/raw/rice/crop_state"
CODE = "district_code_census2011"
YEAR = "agricultural_start_year"
GEO = ROOT / "data/processed/rice/seasonal_geography/reference_geometries.geojson"
INPUT = ROOT / "data/processed/rice/odisha_seasonal/prepared_inputs.csv"
PROTOCOL = ROOT / "docs/Crop_State_Extension.md"
MONTHS = (6, 7, 8)

# Kept in this module so app.py remains the only local launcher. The generated
# JavaScript is an acquisition artifact for the authenticated web Code Editor.
SCRIPT = r'''// Generated by python app.py --prepare-crop-state-export.
// Run in https://code.earthengine.google.com after noncommercial registration.
// Cropland vegetation proxy, NOT a rice-specific mask. No yield labels exported.
var districts = ee.FeatureCollection(__DISTRICTS__);
var ndviSource = ee.ImageCollection('MODIS/061/MOD13Q1');
var soilSource = ee.ImageCollection('ECMWF/ERA5_LAND/DAILY_AGGR');
var landSource = ee.ImageCollection('MODIS/061/MCD12Q1');
var ndviProjection = ee.Image(ndviSource.first()).select('NDVI').projection();
var soilProjection = ee.Image(soilSource.first())
    .select('volumetric_soil_water_layer_1').projection();
var area = ee.Image.pixelArea();
var emptyVI = ee.Image.constant(0).rename('ndvi').updateMask(ee.Image.constant(0));
var emptySoil = ee.Image.constant(0).rename('volumetric_soil_water_layer_1')
  .updateMask(ee.Image.constant(0));

function monthSelection(year, month) {
  // Resolve boundaries to literal ISO dates on the client. No shared loop-date
  // state or computed timestamp comparison enters a server-side filter.
  function iso(date) { return date.toISOString().slice(0, 10); }
  var start = iso(new Date(Date.UTC(year, month-1, 1)));
  var end = month === 8 ? year+'-08-25' : iso(new Date(Date.UTC(year, month, 1)));
  // Group by completion month: source start +16 days is the exclusive end.
  // No August-start composite finishes by Aug24. Late-July starts do finish.
  var viStart = iso(new Date(Date.parse(start)-16*86400000));
  var viEnd = iso(new Date(Date.parse(end)-16*86400000));
  return {month: month, vi: ndviSource.filterDate(viStart, viEnd).map(goodNDVI),
    soil: soilSource.filterDate(start, end).select('volumetric_soil_water_layer_1'),
    expectedDays: month === 6 ? 30 : (month === 7 ? 31 : 24)};
}

function sums(image, geometry, projection) {
  return image.reduceRegion({reducer: ee.Reducer.sum(), geometry: geometry,
    crs: projection, scale: projection.nominalScale(), maxPixels: 1e9, tileScale: 4});
}
function goodNDVI(image) {
  var raw = image.select('NDVI');
  var good = image.select('SummaryQA').eq(0)
    .and(raw.gte(-2000)).and(raw.lte(10000));
  return raw.multiply(0.0001).updateMask(good).rename('ndvi')
    .copyProperties(image, ['system:time_start']);
}
function yearRows(y) {
    var land = ee.Image(landSource.filterDate((y-2)+'-01-01', (y-1)+'-01-01').first())
      .select('LC_Type1');
    var crop = land.eq(12).or(land.eq(14)); // cropland and cropland/natural mosaics
    var monthly = [];
    [6, 7, 8].forEach(function(month) {
      // Composite COMPLETION belongs to month; support can start in prior month.
      // This is not a daily/month-boundary-exact vegetation average.
      var selected = monthSelection(y, month);
      var vi = selected.vi;
      // Fully masked named seeds provide a stable band schema even for an
      // empty source selection. They add no observations or measured values.
      var safeVI = vi.merge(ee.ImageCollection.fromImages([emptyVI]));
      var viMean = safeVI.mean().updateMask(crop);
      var viCount = safeVI.count().unmask(0).updateMask(crop);
      var soil = selected.soil;
      var soilMean = soil.merge(ee.ImageCollection.fromImages([emptySoil])).mean();
      monthly.push({month: month, vi: viMean, viCount: viCount, soil: soilMean,
        viDates: vi.size(), soilDays: soil.size(), expectedDays: selected.expectedDays});
    });
    var rows = districts.map(function(feature) {
      var geometry = feature.geometry();
      var cropArea = ee.Number(sums(area.updateMask(crop).rename('a'), geometry, ndviProjection).get('a'));
      var districtArea = ee.Number(sums(area.rename('a'), geometry, soilProjection).get('a'));
      var properties = feature.toDictionary([__CODE__, 'district_source']);
      properties = properties.set(__YEAR__, y).set('mask_year', y-2)
        .set('crop_proxy_area_m2', cropArea).set('observation_end', y+'-08-24')
        .set('export_version', 2);
      monthly.forEach(function(m) {
        var suffix = ('0'+m.month).slice(-2);
        var n = sums(m.vi.unmask(0).updateMask(crop).multiply(area).rename('value')
          .addBands(m.vi.mask().unmask(0).updateMask(crop).multiply(area).rename('valid'))
          .addBands(m.viCount.multiply(area).rename('count')), geometry, ndviProjection);
        var valid = ee.Number(n.get('valid'));
        var s = sums(m.soil.unmask(0).multiply(area).rename('value')
          .addBands(m.soil.mask().unmask(0).multiply(area).rename('valid')), geometry, soilProjection);
        var soilValid = ee.Number(s.get('valid'));
        properties = properties.set('ndvi_'+suffix,
          ee.Algorithms.If(valid.gt(0), ee.Number(n.get('value')).divide(valid), null))
          .set('ndvi_coverage_'+suffix, ee.Algorithms.If(cropArea.gt(0), valid.divide(cropArea), 0))
          .set('ndvi_mean_observations_'+suffix,
            ee.Algorithms.If(cropArea.gt(0), ee.Number(n.get('count')).divide(cropArea), 0))
          .set('ndvi_composites_'+suffix, m.viDates)
          .set('soil_moisture_'+suffix,
            ee.Algorithms.If(soilValid.gt(0), ee.Number(s.get('value')).divide(soilValid), null))
          .set('soil_coverage_'+suffix, soilValid.divide(districtArea))
          .set('soil_days_'+suffix, m.soilDays).set('expected_days_'+suffix, m.expectedDays);
      });
      return ee.Feature(null, properties); // CSV only; no geometry repeated per row
    });
    return rows;
}
// Check source image counts before creating tasks. Never export an empty
// selection as if it were genuine satellite observations.
var checks = [];
for (var checkYear = 2004; checkYear <= 2017; checkYear++) {
  [6, 7, 8].forEach(function(month) {
    var selected = monthSelection(checkYear, month);
    checks.push(ee.Feature(null, {year: checkYear, month: month,
      ndvi_composites: selected.vi.size(), soil_days: selected.soil.size(),
      expected_days: selected.expectedDays}));
  });
}
ee.FeatureCollection(checks).evaluate(function(result, error) {
  if (error) { print('Source check failed; no export tasks created.', error); return; }
  var bad = result.features.filter(function(f) {
    var p = f.properties;
    return p.ndvi_composites < 1 || p.ndvi_composites > 2 || p.soil_days !== p.expected_days;
  });
  if (bad.length) { print('Source dates missing; no export tasks created.', bad); return; }
  print('Source checks passed: 42 year/month selections. Creating four v2 tasks.');
  [[2004, 2007], [2008, 2011], [2012, 2014], [2015, 2017]].forEach(function(block) {
    var tables = [];
    for (var year = block[0]; year <= block[1]; year++) { tables.push(yearRows(year)); }
    Export.table.toDrive({collection: ee.FeatureCollection(tables).flatten(),
      description: 'Odisha_Crop_State_'+block[0]+'_'+block[1]+'_v2',
      fileNamePrefix: 'Odisha_Crop_State_'+block[0]+'_'+block[1]+'_v2', fileFormat: 'CSV'});
  });
  print('Start the four v2 tasks; do not restart old failed tasks.');
});
Map.centerObject(districts, 7);
Map.addLayer(districts, {color: '245d92'}, 'Study districts');
print('Checking source dates. Tasks will appear only after checks pass.');
'''


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_json(path, value):
    path.write_text(json.dumps(value, indent=2, allow_nan=False)+"\n", encoding="utf-8", newline="\n")


def prepare_export():
    """No network or credentials required; exact existing polygons, no smoothing."""
    OUT.mkdir(parents=True, exist_ok=True)
    RAW.mkdir(parents=True, exist_ok=True)
    geo = json.loads(GEO.read_text(encoding="utf-8"))
    source = pd.read_csv(INPUT, dtype={CODE: str})
    names = source[[CODE, "district_source"]].drop_duplicates().set_index(CODE).district_source.to_dict()
    features = []
    for feature in geo["features"]:
        properties = feature["properties"]
        if properties["state_code_census2011"] != "21":
            continue
        code = properties[CODE]
        features.append({"type": "Feature", "geometry": feature["geometry"],
                         "properties": {CODE: code, "district_source": names[code]}})
    if len(features) != 30 or {f["properties"][CODE] for f in features} != set(names):
        raise ValueError("Expected the same 30 source districts")
    script = SCRIPT.replace("__DISTRICTS__", json.dumps({"type": "FeatureCollection", "features": features}, separators=(",", ":")))
    script = script.replace("__CODE__", json.dumps(CODE)).replace("__YEAR__", json.dumps(YEAR))
    path = OUT / "Earth_Engine_Export.js"
    path.write_text(script, encoding="utf-8", newline="\n")
    write_json(OUT / "export_plan.json", {
        "status": "prepared_not_executed", "version": 2, "expected_rows": 420,
        "years": [2004, 2017], "districts": 30, "issue_date": "08-31", "observation_end": "08-24",
        "mask": "MCD12Q1 LC_Type1 12 or 14 from Y-2; mixed cropland, not rice-specific",
        "source_sha256": {str(p.relative_to(ROOT)).replace('\\', '/'): digest(p)
                          for p in (GEO, INPUT, PROTOCOL, Path(__file__))},
        "export_script_sha256": digest(path), "requires": "User Earth Engine access and four completed Drive exports",
    })
    return str(path)


def check_import():
    """Reject incomplete keys, future dates, bad ranges and missing soil data.

    A CSV's own metadata is not proof that its cloud computation ran correctly.
    The script still requires execution/review in the authenticated Code Editor.
    """
    plan_path = OUT / "export_plan.json"
    if not plan_path.exists():
        raise ValueError("Run --prepare-crop-state-export first")
    plan = json.loads(plan_path.read_text(encoding="utf-8"))
    for name, expected in plan["source_sha256"].items():
        if digest(ROOT / name) != expected:
            raise ValueError("Export plan inputs changed; review and regenerate before importing")
    if digest(OUT / "Earth_Engine_Export.js") != plan["export_script_sha256"]:
        raise ValueError("Export script changed")
    files = sorted(RAW.glob("Odisha_Crop_State_*_v2.csv"))
    if len(files) != 4:
        raise ValueError(f"Expected four Earth Engine export CSVs in {RAW}; found {len(files)}")
    frame = pd.concat([pd.read_csv(p, dtype={CODE: str}) for p in files], ignore_index=True)
    source = pd.read_csv(INPUT, dtype={CODE: str})
    source = source.loc[source[YEAR].between(2004, 2017)].copy()
    keys = [CODE, YEAR]
    if len(frame) != 420 or frame.duplicated(keys).any():
        raise ValueError("Expected 420 unique district-years; no silent dropping or deduplication")
    if set(map(tuple, frame[keys].to_numpy())) != set(map(tuple, source[keys].to_numpy())):
        raise ValueError("District-year key set does not match the fixed cohort")
    if not frame.mask_year.eq(frame[YEAR]-2).all() or not frame.export_version.eq(2).all():
        raise ValueError("Wrong land-cover timing or export version")
    if not frame.observation_end.eq(frame[YEAR].astype(str)+"-08-24").all():
        raise ValueError("Unexpected observation cutoff")
    if not np.isfinite(frame.crop_proxy_area_m2).all() or (frame.crop_proxy_area_m2 <= 0).any():
        raise ValueError("No mapped cropland in one or more districts")
    reports = []
    for month, expected_days in ((6, 30), (7, 31), (8, 24)):
        suffix = f"{month:02d}"
        for prefix in ("ndvi_coverage_", "soil_coverage_"):
            values = frame[prefix+suffix]
            if not np.isfinite(values).all() or not values.between(0, 1+1e-6).all():
                raise ValueError("Invalid spatial coverage")
        if not frame["soil_days_"+suffix].eq(expected_days).all() or not frame["expected_days_"+suffix].eq(expected_days).all():
            raise ValueError("Missing daily soil images")
        if not frame["ndvi_composites_"+suffix].between(1, 2).all():
            raise ValueError("Unexpected MODIS composite count")
        counts = frame["ndvi_mean_observations_"+suffix]
        if not np.isfinite(counts).all() or not counts.between(0, frame["ndvi_composites_"+suffix]+1e-6).all():
            raise ValueError("Invalid NDVI observation counts")
        ndvi = frame["ndvi_"+suffix]
        if not ndvi.dropna().between(-.2, 1).all():
            raise ValueError("Unscaled, nonfinite or invalid NDVI")
        soil = frame["soil_moisture_"+suffix]
        if not np.isfinite(soil).all() or not soil.between(0, 1).all() or (frame["soil_coverage_"+suffix] < .5).any():
            raise ValueError("Incomplete soil coverage or invalid volumetric soil water")
        low = frame["ndvi_coverage_"+suffix] < .25
        frame.loc[low, "ndvi_"+suffix] = np.nan
        reports.append({"month": month, "ndvi_missing_rows_after_coverage_rule": int(frame["ndvi_"+suffix].isna().sum()),
                        "soil_minimum_coverage": float(frame["soil_coverage_"+suffix].min())})
    features = [f"{prefix}_{m:02d}" for prefix in ("ndvi", "soil_moisture") for m in MONTHS]
    # The checked join is one-to-one on Census reference district plus start year.
    # Harvest yield, area and production are never exported or used as new Xs.
    joined = source.merge(frame[keys+features], on=keys, how="left", validate="one_to_one", indicator=True)
    if not joined._merge.eq("both").all():
        raise ValueError("Unmatched yield labels")
    joined.drop(columns="_merge").to_csv(OUT / "prepared_inputs.csv", index=False, lineterminator="\n")
    report = {"status": "import_validated_not_trained", "rows": len(joined), "new_predictors": features,
              "coverage": reports, "raw_sha256": {p.name: digest(p) for p in files},
              "prepared_sha256": digest(OUT / "prepared_inputs.csv"),
              "cloud_execution_independently_verified": False}
    write_json(OUT / "import_audit.json", report)
    return report
